import { readdirSync, readFileSync } from "node:fs";
import { join, posix } from "node:path";

/**
 * Runtime assets of the embedded dashboard: every .html, .js and .css file
 * under src/engine/dashboard (nested module folders included). Server-side
 * TypeScript and tests live in the same directory but are never assets.
 */
const assetFile = /\.(html|js|css)$/;
const testFile = /\.test\.[a-z]+$/;

/** Sorted, forward-slash relative names, so generation is deterministic. */
export function scanDashboardAssets(directory: string, prefix = ""): string[] {
  const names: string[] = [];
  for (const entry of readdirSync(join(directory, prefix), {
    withFileTypes: true,
  })) {
    const name = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory())
      names.push(...scanDashboardAssets(directory, name));
    else if (entry.isFile() && assetFile.test(name) && !testFile.test(name))
      names.push(name);
  }
  return names.sort();
}

/** Source of src/engine/assets.ts for the given asset names. */
export function renderAssetsModule(names: string[]): string {
  const lines = [
    "// Generated by scripts/embed.ts from src/engine/dashboard; do not edit.",
    ...names.map(
      (name, index) =>
        `import asset${index} from "./assets/${name}.txt" with { type: "text" };`,
    ),
    "export const embeddedAssets: Record<string, string> = {",
    ...names.map((name, index) => `  ${JSON.stringify(name)}: asset${index},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

/** Public path of the run viewer script, which is embedded as run-viewer.js. */
const publicAliases: Record<string, string> = { "/runs.js": "run-viewer.js" };
const stripComments = (code: string) =>
  code.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:\\])\/\/.*$/gm, "$1");
/** Static import and re-export specifiers, in source order. */
function staticSpecifiers(source: string): string[] {
  const found: string[] = [];
  for (const match of stripComments(source).matchAll(
    /(?:\bfrom\s*|\bimport\s*)(["'])([^"'\n]+)\1/g,
  ))
    found.push(match[2] ?? "");
  return found;
}
const startMarker =
  "<!-- modulepreload:start (generated by scripts/embed.ts; do not edit) -->";
const endMarker = "<!-- modulepreload:end -->";

/**
 * Every module the page loads, as the public paths the browser requests, in
 * the order a breadth-first walk from the page's module scripts finds them.
 * The page names its entries; each module's own imports name the rest, so a
 * new module is picked up without a list to edit.
 */
export function modulePaths(directory: string, html: string): string[] {
  const fileOf = (path: string) =>
    publicAliases[path] ?? path.replace(/^\//, "");
  const entries = [
    ...html.matchAll(
      /<script\s+type="module"\s+src="(\/[^"#?]+)"\s*><\/script>/g,
    ),
  ].map((match) => match[1] ?? "");
  const seen = new Set<string>();
  const order: string[] = [];
  const queue = [...entries];
  for (let at = 0; at < queue.length; at++) {
    const path = queue[at] as string;
    if (seen.has(path)) continue;
    seen.add(path);
    order.push(path);
    const file = fileOf(path);
    const base = posix.dirname(file);
    for (const value of staticSpecifiers(
      readFileSync(join(directory, file), "utf8"),
    )) {
      if (!/^(?:\.\.?\/|\/)/.test(value))
        throw new Error(`${file}: "${value}" is not a browser-resolvable path`);
      queue.push(
        value.startsWith("/")
          ? value
          : `/${posix.normalize(posix.join(base, value))}`,
      );
    }
  }
  return order;
}

/** The index page with its generated modulepreload block brought up to date. */
export function withModulePreload(directory: string, html: string): string {
  const links = modulePaths(directory, html)
    .map((path) => `    <link rel="modulepreload" href="${path}" />`)
    .join("\n");
  const block = `${startMarker}\n${links}\n    ${endMarker}`;
  const from = html.indexOf(startMarker);
  if (from >= 0) {
    const end = html.indexOf(endMarker, from);
    if (end < 0)
      throw new Error("index.html: unterminated modulepreload block");
    return html.slice(0, from) + block + html.slice(end + endMarker.length);
  }
  // First time: just before the first module script.
  const anchor = html.search(/<script\s+type="module"/);
  if (anchor < 0) throw new Error("index.html: no module script");
  const indent = "    ";
  return `${html.slice(0, anchor)}${block}\n${indent}${html.slice(anchor)}`;
}
