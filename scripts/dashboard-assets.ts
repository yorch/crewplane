import { readdirSync } from "node:fs";
import { join } from "node:path";

/**
 * Runtime assets of the embedded dashboard: every .html, .js and .css file
 * under src/engine/dashboard (nested module folders included). Server-side
 * TypeScript and tests live in the same directory but are never assets.
 */
const assetFile = /\.(html|js|css)$/;
const testFile = /\.test\.[a-z]+$/;

/** Sorted, forward-slash relative names, so generation is deterministic. */
export function scanDashboardAssets(directory: string, prefix = ""): string[] {
  const names: string[] = [];
  for (const entry of readdirSync(join(directory, prefix), {
    withFileTypes: true,
  })) {
    const name = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory())
      names.push(...scanDashboardAssets(directory, name));
    else if (entry.isFile() && assetFile.test(name) && !testFile.test(name))
      names.push(name);
  }
  return names.sort();
}

/** Source of src/engine/assets.ts for the given asset names. */
export function renderAssetsModule(names: string[]): string {
  const lines = [
    "// Generated by scripts/embed.ts from src/engine/dashboard; do not edit.",
    ...names.map(
      (name, index) =>
        `import asset${index} from "./assets/${name}.txt" with { type: "text" };`,
    ),
    "export const embeddedAssets: Record<string, string> = {",
    ...names.map((name, index) => `  ${JSON.stringify(name)}: asset${index},`),
    "};",
    "",
  ];
  return lines.join("\n");
}
